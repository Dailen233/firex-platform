"""Capture storage: atomic persistence with a server receipt, safe recovery, idempotency.

Persistence order: write files + server receipt into a temp directory, atomically
rename into place, then commit the SQLite transaction. A receipt (``manifest.json``)
is generated by the server and never accepted from the client; it records the
identity needed to confirm ownership when a directory already exists (for example
after a crash between the rename and the commit).

On encountering an existing same-named directory, the code never deletes it
blindly. It verifies path boundary/type, reads the receipt, checks the receipt
against the current run + content, and checks the actual files against the receipt
hashes. Only a directory that provably belongs to the SAME request is reused
(preserving the original ``received_at``); a different run/content is a 409, and a
missing/corrupt/unverifiable directory is kept and reported as a recovery error.
"""
from __future__ import annotations

import hashlib
import json
import math
import os
import shutil
import sqlite3
import tempfile
from datetime import datetime, timezone
from pathlib import Path

from . import db
from .capture_metadata import CaptureMetadata, canonical_metadata_json
from .errors import CaptureValidationError, ConflictError, RecoveryError
from .models import SCHEMA_VERSION, CaptureRecord, RunRecord
from .time_contract import observation_time_s_for_real, observation_time_s_for_simulation

STATUS_QUEUED = "queued"

_ORIGINAL_FILENAME = "original.bin"
_RAW_METADATA_FILENAME = "metadata.raw.txt"
_NORMALIZED_METADATA_FILENAME = "metadata.normalized.json"
_MANIFEST_FILENAME = "manifest.json"
_MANIFEST_FORMAT_VERSION = "1"


def compute_observation_time(run: RunRecord, meta: CaptureMetadata) -> float:
    """Compute observation_time_s from the run's time contract and the capture time."""
    if run.input_source == "simulation":
        if run.simulation_time_origin_s is None:
            raise CaptureValidationError(
                "run has no simulation_time_origin_s; time contract not configured", "TIME_NOT_CONFIGURED"
            )
        if meta.simulation_time_s is None:
            raise CaptureValidationError("simulation_time_s is required for a simulation run", "INVALID_TIME")
        if meta.captured_at is not None:
            raise CaptureValidationError("captured_at must not be set for a simulation run", "INVALID_TIME")
        obs = observation_time_s_for_simulation(meta.simulation_time_s, run.simulation_time_origin_s)
    else:  # real
        if run.time_origin_utc is None:
            raise CaptureValidationError(
                "run has no time_origin_utc; time contract not configured", "TIME_NOT_CONFIGURED"
            )
        if meta.captured_at is None:
            raise CaptureValidationError("captured_at is required for a real run", "INVALID_TIME")
        if meta.simulation_time_s is not None:
            raise CaptureValidationError("simulation_time_s must not be set for a real run", "INVALID_TIME")
        obs = observation_time_s_for_real(meta.captured_at, run.time_origin_utc)
    if not math.isfinite(obs) or obs < 0:
        raise CaptureValidationError(
            "observation time must be finite and not before the run origin", "INVALID_TIME"
        )
    return obs


def _validate_binding(run: RunRecord, meta: CaptureMetadata) -> None:
    if meta.scene_id != run.scene_id or meta.asset_version != run.asset_version:
        raise CaptureValidationError("metadata scene_id/asset_version must match the run", "METADATA_MISMATCH")
    if run.coordinate_frame_id is None:
        raise CaptureValidationError("run has no coordinate_frame_id; cannot validate capture pose", "METADATA_MISMATCH")
    if meta.coordinate_frame_id != run.coordinate_frame_id:
        raise CaptureValidationError("metadata coordinate_frame_id must match the run", "METADATA_MISMATCH")


def capture_file_path(captures_dir: Path, storage_key: str, filename: str) -> Path:
    """Path under captures_dir for a stored file (storage_key is a validated safe id)."""
    return captures_dir / storage_key / filename


def _build_manifest(
    capture_id: str, run_id: str, byte_size: int, content_sha: str, metadata_sha: str, received_at: datetime
) -> dict:
    return {
        "format_version": _MANIFEST_FORMAT_VERSION,
        "capture_id": capture_id,
        "run_id": run_id,
        "byte_size": byte_size,
        "content_sha256": content_sha,
        "metadata_sha256": metadata_sha,
        "received_at": received_at.isoformat(),
    }


def _read_manifest(final_dir: Path) -> dict | None:
    try:
        return json.loads((final_dir / _MANIFEST_FILENAME).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError, UnicodeDecodeError):
        return None


def _manifest_is_well_formed(manifest: object) -> bool:
    if not isinstance(manifest, dict):
        return False
    return (
        manifest.get("format_version") == _MANIFEST_FORMAT_VERSION
        and isinstance(manifest.get("capture_id"), str)
        and isinstance(manifest.get("run_id"), str)
        and isinstance(manifest.get("byte_size"), int)
        and isinstance(manifest.get("content_sha256"), str)
        and isinstance(manifest.get("metadata_sha256"), str)
        and isinstance(manifest.get("received_at"), str)
    )


def _sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _files_match(final_dir: Path, content_sha: str, metadata_sha: str, byte_size: int) -> bool:
    original = final_dir / _ORIGINAL_FILENAME
    normalized = final_dir / _NORMALIZED_METADATA_FILENAME
    raw = final_dir / _RAW_METADATA_FILENAME
    if not original.is_file() or not normalized.is_file() or not raw.is_file():
        return False
    if original.stat().st_size != byte_size:
        return False
    if _sha256_file(original) != content_sha:
        return False
    return _sha256_file(normalized) == metadata_sha


def _recover_capture_files(
    final_dir: Path, capture_id: str, run_id: str, content_sha: str, metadata_sha: str, byte_size: int
) -> datetime:
    """Recover a landed-but-uncommitted directory; returns the original received_at.

    Never deletes an unverifiable directory: it is kept and reported. Only a
    directory whose receipt AND files both match the current request is reused.
    """
    if final_dir.is_symlink():
        raise RecoveryError(f"capture path is a symlink; refusing to auto-confirm: {capture_id}")
    if not final_dir.is_dir():
        raise RecoveryError(f"capture path exists but is not a directory: {capture_id}")

    manifest = _read_manifest(final_dir)
    if not _manifest_is_well_formed(manifest):
        raise RecoveryError(
            f"capture directory has no valid receipt; cannot auto-confirm ownership: {capture_id}"
        )
    assert manifest is not None  # narrowed by _manifest_is_well_formed

    if manifest.get("capture_id") != capture_id:
        raise RecoveryError(
            f"capture receipt belongs to a different capture_id; cannot auto-confirm: {capture_id}"
        )

    same_request = (
        manifest.get("run_id") == run_id
        and manifest.get("content_sha256") == content_sha
        and manifest.get("metadata_sha256") == metadata_sha
        and manifest.get("byte_size") == byte_size
    )
    if not same_request:
        raise ConflictError(f"capture_id {capture_id} already stored for a different run or content")

    if not _files_match(final_dir, content_sha, metadata_sha, byte_size):
        raise RecoveryError(
            f"capture directory content does not match its receipt; kept for inspection: {capture_id}"
        )

    try:
        return datetime.fromisoformat(manifest["received_at"])
    except (KeyError, ValueError) as exc:
        raise RecoveryError(f"capture receipt has invalid received_at: {capture_id}") from exc


def _persist_capture_files(
    captures_dir: Path,
    capture_id: str,
    run_id: str,
    image_bytes: bytes,
    raw_meta: str,
    normalized_meta: str,
    content_sha: str,
    metadata_sha: str,
    received_at: datetime,
) -> datetime | None:
    """Write new files + receipt, or recover a matching orphan.

    Returns the original ``received_at`` when an existing directory was reused,
    or ``None`` when a fresh directory was written (use the newly-inserted time).
    """
    captures_dir.mkdir(parents=True, exist_ok=True)
    final_dir = captures_dir / capture_id

    if final_dir.exists() or final_dir.is_symlink():
        return _recover_capture_files(final_dir, capture_id, run_id, content_sha, metadata_sha, len(image_bytes))

    tmp_dir = Path(tempfile.mkdtemp(dir=captures_dir, prefix=".tmp-"))
    try:
        (tmp_dir / _ORIGINAL_FILENAME).write_bytes(image_bytes)
        (tmp_dir / _RAW_METADATA_FILENAME).write_text(raw_meta, encoding="utf-8")
        (tmp_dir / _NORMALIZED_METADATA_FILENAME).write_text(normalized_meta, encoding="utf-8")
        (tmp_dir / _MANIFEST_FILENAME).write_text(
            json.dumps(
                _build_manifest(capture_id, run_id, len(image_bytes), content_sha, metadata_sha, received_at)
            ),
            encoding="utf-8",
        )
        os.replace(tmp_dir, final_dir)  # atomic directory rename on the same filesystem
    except Exception:
        shutil.rmtree(tmp_dir, ignore_errors=True)
        raise
    return None


def save_capture(
    db_path: Path,
    captures_dir: Path,
    run: RunRecord,
    meta: CaptureMetadata,
    raw_meta_text: str,
    image_bytes: bytes,
) -> tuple[CaptureRecord, bool]:
    """Persist a capture atomically. Returns (record, is_new).

    Idempotency: same run + capture_id + image bytes + normalized metadata
    returns the existing record without touching files or received_at.
    Conflict (same capture_id, different content) raises 409.
    """
    _validate_binding(run, meta)
    observation_time_s = compute_observation_time(run, meta)
    content_sha = hashlib.sha256(image_bytes).hexdigest()
    normalized = canonical_metadata_json(meta)
    metadata_sha = hashlib.sha256(normalized.encode("utf-8")).hexdigest()
    storage_key = meta.capture_id
    received_at = datetime.now(timezone.utc)

    conn = db.connect(db_path)
    try:
        conn.execute("BEGIN IMMEDIATE")
        try:
            conn.execute(
                "INSERT INTO captures (capture_id, run_id, scene_id, asset_version, coordinate_frame_id, "
                "input_source, width, height, observation_time_s, received_at, content_sha256, byte_size, "
                "metadata_sha256, storage_key, status, schema_version) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
                (
                    meta.capture_id,
                    run.run_id,
                    meta.scene_id,
                    meta.asset_version,
                    meta.coordinate_frame_id,
                    run.input_source,
                    meta.width,
                    meta.height,
                    observation_time_s,
                    received_at.isoformat(),
                    content_sha,
                    len(image_bytes),
                    metadata_sha,
                    storage_key,
                    STATUS_QUEUED,
                    SCHEMA_VERSION,
                ),
            )
        except sqlite3.IntegrityError:
            conn.rollback()
            row = conn.execute("SELECT * FROM captures WHERE capture_id = ?", (meta.capture_id,)).fetchone()
            if row is not None:
                existing = _row_to_record(row)
                if (
                    existing.run_id == run.run_id
                    and existing.content_sha256 == content_sha
                    and row["metadata_sha256"] == metadata_sha
                ):
                    return existing, False
            raise ConflictError(f"capture_id {meta.capture_id} already used with different content")

        try:
            reused_received_at = _persist_capture_files(
                captures_dir,
                storage_key,
                run.run_id,
                image_bytes,
                raw_meta_text,
                normalized,
                content_sha,
                metadata_sha,
                received_at,
            )
        except Exception:
            conn.rollback()
            raise

        if reused_received_at is not None:
            conn.execute(
                "UPDATE captures SET received_at = ? WHERE capture_id = ?",
                (reused_received_at.isoformat(), storage_key),
            )
            received_at = reused_received_at
        conn.commit()
    except Exception:
        try:
            conn.rollback()
        except Exception:
            pass
        raise
    finally:
        conn.close()

    return (
        CaptureRecord(
            capture_id=meta.capture_id,
            run_id=run.run_id,
            received_at=received_at,
            observation_time_s=observation_time_s,
            content_sha256=content_sha,
            byte_size=len(image_bytes),
            status=STATUS_QUEUED,
            schema_version=SCHEMA_VERSION,
            storage_key=storage_key,
        ),
        True,
    )


def get_capture(db_path: Path, capture_id: str) -> CaptureRecord | None:
    conn = db.connect(db_path)
    try:
        row = conn.execute("SELECT * FROM captures WHERE capture_id = ?", (capture_id,)).fetchone()
    finally:
        conn.close()
    if row is None:
        return None
    return _row_to_record(row)


def _row_to_record(row: sqlite3.Row) -> CaptureRecord:
    return CaptureRecord(
        capture_id=row["capture_id"],
        run_id=row["run_id"],
        received_at=datetime.fromisoformat(row["received_at"]),
        observation_time_s=row["observation_time_s"],
        content_sha256=row["content_sha256"],
        byte_size=row["byte_size"],
        status=row["status"],
        schema_version=row["schema_version"],
        storage_key=row["storage_key"],
    )
